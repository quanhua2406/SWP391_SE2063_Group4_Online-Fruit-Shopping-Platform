package com.mycompany.onlinefruitshopping.dao.promotion;

import com.mycompany.onlinefruitshopping.model.CartItem;
import com.mycompany.onlinefruitshopping.utils.PromotionRules;
import java.math.BigDecimal;
import java.sql.*;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

/** Read-only selling prices. Base prices and historical order items never change. */
public final class PromotionPricing {
    private PromotionPricing() { }

    public static String customerVariants() {
        return customerVariants(PromotionRules.now());
    }

    // The timestamp is generated by the server, never supplied as SQL by a client.
    public static String customerVariants(LocalDateTime now) {
        String time = now.format(DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss"));
        return """
            (SELECT v.variant_id, v.product_id, v.sku, v.unit, v.weight_value,
                    v.packaging_type, v.quality_grade, v.created_at, prices.price
             FROM product_variants v
             JOIN (
                 SELECT offers.variant_id, MIN(offers.price) AS price
                 FROM (
                     SELECT variant_id, price FROM product_variants
                     UNION ALL
                     SELECT pv.variant_id,
                            CASE WHEN pr.discount_type = 'PERCENT'
                                 THEN CASE WHEN ROUND(pv.price * pr.discount_value / 100, 0) >= pv.price THEN 0
                                           ELSE pv.price - ROUND(pv.price * pr.discount_value / 100, 0) END
                                 WHEN pr.discount_value >= pv.price THEN 0
                                 ELSE pv.price - pr.discount_value END AS price
                     FROM product_variants pv
                     JOIN products p ON p.product_id = pv.product_id
                     JOIN shops s ON s.shop_id = p.shop_id
                     JOIN promotion_products pp ON pp.product_id = p.product_id
                     JOIN promotions pr ON pr.promotion_id = pp.promotion_id AND pr.shop_id = p.shop_id
                     WHERE pr.is_active = 1 AND pr.is_deleted = 0
                       AND pr.starts_at <= CAST('%1$s' AS datetime2)
                       AND pr.ends_at > CAST('%1$s' AS datetime2)
                       AND p.status = 'published' AND p.hidden_by_admin = 0 AND s.status = 'active'
                     UNION ALL
                     SELECT pv.variant_id, vp.promo_price
                     FROM product_variants pv
                     JOIN products p ON p.product_id = pv.product_id
                     JOIN shops s ON s.shop_id = p.shop_id
                     JOIN variant_promotions vp ON vp.variant_id = pv.variant_id
                     WHERE vp.status = 'approved'
                       AND vp.start_date <= CAST(CAST('%1$s' AS datetime2) AS date)
                       AND vp.end_date >= CAST(CAST('%1$s' AS datetime2) AS date)
                       AND p.status = 'published' AND p.hidden_by_admin = 0 AND s.status = 'active'
                 ) offers
                 GROUP BY offers.variant_id
             ) prices ON prices.variant_id = v.variant_id)
            """.formatted(time);
    }

    /** Called inside the order transaction, before inserting the order/payment snapshot. */
    public static void validateCheckoutPrices(Connection connection, int shopId, List<CartItem> items)
            throws SQLException {
        if (items == null || items.isEmpty()) throw new IllegalArgumentException("Giỏ hàng đang trống.");
        String sql = "SELECT pv.price FROM " + customerVariants() + " pv "
                + "JOIN products p ON p.product_id = pv.product_id "
                + "JOIN shops s ON s.shop_id = p.shop_id "
                + "WHERE pv.variant_id = ? AND p.shop_id = ? AND p.status = 'published' "
                + "AND p.hidden_by_admin = 0 AND s.status = 'active'";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            for (CartItem item : items) {
                ps.setInt(1, item.getVariantId());
                ps.setInt(2, shopId);
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) throw new IllegalArgumentException("Sản phẩm không còn được bán tại cửa hàng này.");
                    if (rs.getBigDecimal("price").compareTo(BigDecimal.valueOf(item.getUnitPrice())) != 0) {
                        throw new IllegalArgumentException("Giá hoặc khuyến mãi vừa thay đổi. Vui lòng tải lại trang thanh toán để xác nhận giá mới.");
                    }
                }
            }
        }
    }
}
