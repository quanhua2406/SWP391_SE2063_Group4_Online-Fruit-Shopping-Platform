package com.mycompany.onlinefruitshopping.support;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;

/**
 * Isolated H2 database for the delivery module tests.
 * Schema follows the canonical columns of the shared database, so the real
 * DAO statements (attempts, payments, canonical statuses) are executed as-is.
 * SQL Server locking hints are not certified here.
 */
public final class ModuleDatabase {
    public final String url;

    public ModuleDatabase() {
        url = "jdbc:h2:mem:module_" + UUID.randomUUID() + ";MODE=MSSQLServer;DB_CLOSE_DELAY=-1";
        try {
            create();
        } catch (SQLException e) {
            throw new IllegalStateException("Không tạo được database test.", e);
        }
    }

    public Connection open() throws SQLException {
        return DriverManager.getConnection(url);
    }

    /** SQL Server's SYSDATETIME() replacement for H2. */
    public static java.sql.Timestamp sysdatetime() {
        return new java.sql.Timestamp(System.currentTimeMillis());
    }

    private void create() throws SQLException {
        try (Connection c = open(); Statement s = c.createStatement()) {
            s.execute("CREATE ALIAS SYSDATETIME FOR \"com.mycompany.onlinefruitshopping.support.ModuleDatabase.sysdatetime\"");
            s.execute("CREATE TABLE roles(role_id INT PRIMARY KEY, role_name VARCHAR(40))");
            s.execute("CREATE TABLE users(user_id INT PRIMARY KEY, full_name VARCHAR(100), status VARCHAR(20))");
            s.execute("CREATE TABLE user_roles(user_id INT, role_id INT)");
            s.execute("CREATE TABLE shops(shop_id INT PRIMARY KEY, owner_id INT, shop_name VARCHAR(100), status VARCHAR(20))");
            s.execute("CREATE TABLE shop_delivery_staff(shop_id INT, shipper_id INT, status VARCHAR(20))");
            s.execute("""
                CREATE TABLE user_addresses(address_id INT PRIMARY KEY, user_id INT,
                    recipient_name VARCHAR(100), phone VARCHAR(20), address_line VARCHAR(255),
                    ward VARCHAR(100), district VARCHAR(100), province VARCHAR(100))
                """);
            s.execute("""
                CREATE TABLE orders(order_id INT PRIMARY KEY, shop_id INT, user_id INT, address_id INT,
                    status VARCHAR(30), total_amount DECIMAL(12,2), voucher_id INT)
                """);
            s.execute("""
                CREATE TABLE payments(order_id INT, method VARCHAR(20), status VARCHAR(20),
                    amount DECIMAL(12,2), transaction_ref VARCHAR(100), paid_at TIMESTAMP)
                """);
            s.execute("""
                CREATE TABLE deliveries(delivery_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INT,
                    staff_id INT, status VARCHAR(30), note VARCHAR(255), proof_image_url VARCHAR(500))
                """);
            s.execute("""
                CREATE TABLE delivery_attempts(attempt_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    delivery_id INT, shipper_id INT, assigned_by INT,
                    delivery_status VARCHAR(30) DEFAULT 'Assigned', version INT DEFAULT 0,
                    receiver_name VARCHAR(100), receiver_phone VARCHAR(20),
                    shipping_address VARCHAR(1000), pickup_address VARCHAR(1000), note VARCHAR(255),
                    accepted_at TIMESTAMP, pickup_time TIMESTAMP, delivered_time TIMESTAMP,
                    closed_at TIMESTAMP)
                """);
            s.execute("""
                CREATE TABLE notifications(notification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INT, title VARCHAR(255), content VARCHAR(500), is_read INT DEFAULT 0,
                    read_at TIMESTAMP, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)
                """);
            s.execute("""
                CREATE TABLE order_status_history(history_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    order_id INT, status VARCHAR(30), changed_by INT,
                    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)
                """);
            s.execute("""
                CREATE TABLE products(product_id INT PRIMARY KEY, product_name VARCHAR(100),
                    shop_id INT, status VARCHAR(20), hidden_by_admin INT DEFAULT 0)
                """);
            s.execute("""
                CREATE TABLE product_variants(variant_id INT PRIMARY KEY, product_id INT,
                    sku VARCHAR(50), price DECIMAL(12,2))
                """);
            s.execute("""
                CREATE TABLE order_items(order_item_id INT PRIMARY KEY, order_id INT,
                    variant_id INT, unit_price DECIMAL(12,2), quantity DECIMAL(10,2))
                """);
            s.execute("""
                CREATE TABLE coupons(coupon_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    shop_id INT, code VARCHAR(30), coupon_name VARCHAR(150), description VARCHAR(500),
                    discount_type VARCHAR(20), discount_value DECIMAL(12,2), max_discount DECIMAL(12,2),
                    min_order_amount DECIMAL(12,2), total_limit INT, per_customer_limit INT,
                    starts_at TIMESTAMP, ends_at TIMESTAMP, is_active BOOLEAN DEFAULT FALSE,
                    is_deleted BOOLEAN DEFAULT FALSE, version INT DEFAULT 0,
                    created_at TIMESTAMP, updated_at TIMESTAMP)
                """);
            s.execute("""
                CREATE TABLE coupon_usages(usage_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    coupon_id INT, shop_id INT, order_id INT, customer_id INT, code_snapshot VARCHAR(30),
                    subtotal DECIMAL(12,2), discount_amount DECIMAL(12,2), final_amount DECIMAL(12,2),
                    used_at TIMESTAMP, usage_status VARCHAR(20), removed_at TIMESTAMP)
                """);

            s.execute("INSERT INTO roles VALUES (1,'ShopOwner'),(2,'DeliveryStaff'),(3,'Customer')");
            s.execute("""
                INSERT INTO users VALUES (10,'Owner A','active'),(11,'Owner B','active'),
                    (20,'Shipper A','active'),(21,'Shipper B','active'),(30,'Customer A','active'),
                    (31,'Customer B','active')
                """);
            s.execute("INSERT INTO user_roles VALUES (10,1),(11,1),(20,2),(21,2),(30,3),(31,3)");
            s.execute("INSERT INTO shops VALUES (1,10,'Shop A','active'),(2,11,'Shop B','active')");
            s.execute("INSERT INTO shop_delivery_staff VALUES (1,20,'Active'),(1,21,'Active')");
            s.execute("""
                INSERT INTO user_addresses VALUES (1,30,'Customer A','0900000000','1 Test street',
                    'Ward 1','District 1','HCM')
                """);
            s.execute("""
                INSERT INTO orders VALUES (100,1,30,1,'shipping',500.00,NULL),
                    (101,1,30,1,'preparing',300.00,NULL),(102,2,30,1,'preparing',200.00,NULL),
                    (103,1,30,1,'pending_confirmation',75000.00,NULL)
                """);
            s.execute("""
                INSERT INTO payments VALUES (100,'cod','pending',500.00,NULL,NULL),
                    (101,'cod','pending',300.00,NULL,NULL),(102,'cod','pending',200.00,NULL,NULL),
                    (103,'cod','pending',75000.00,NULL,NULL)
                """);
            s.execute("INSERT INTO products VALUES (1,'Apple',1,'published',0)");
            s.execute("INSERT INTO product_variants VALUES (1,1,'APPLE-1KG',100000.00)");
            s.execute("INSERT INTO order_items VALUES (3,103,1,100000.00,0.5)");
            s.execute("INSERT INTO deliveries(delivery_id,order_id,staff_id,status) VALUES (1,100,20,'delivering')");
            s.execute("""
                INSERT INTO delivery_attempts(attempt_id,delivery_id,shipper_id,assigned_by,delivery_status,
                    version,receiver_name,receiver_phone,shipping_address,pickup_address)
                VALUES (1,1,20,10,'Delivering',0,'Customer A','0900000000',
                    '1 Test street, Ward 1, District 1, HCM','Shop pickup')
                """);
            // Identities inserted explicitly above must continue after the seeded rows.
            s.execute("ALTER TABLE deliveries ALTER COLUMN delivery_id RESTART WITH 2");
            s.execute("ALTER TABLE delivery_attempts ALTER COLUMN attempt_id RESTART WITH 2");
        }
    }

    /** Convenience helpers for assertions inside tests. */
    public int count(String sql) throws SQLException {
        return Integer.parseInt(scalar(sql));
    }

    public String scalar(String sql) throws SQLException {
        try (Connection c = open();
             Statement s = c.createStatement();
             java.sql.ResultSet r = s.executeQuery(sql)) {
            if (!r.next()) throw new SQLException("Query trả về không có dòng nào: " + sql);
            return r.getString(1);
        }
    }

    public void exec(String... statements) throws SQLException {
        try (Connection c = open(); Statement s = c.createStatement()) {
            for (String sql : statements) s.execute(sql);
        }
    }
}
